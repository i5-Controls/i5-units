use crate::values::{compact, ordered_entries, Result};
use serde_json::Value;

fn pretty(value: &Value) -> Result<String> {
    Ok(format!("{}\n", layout(value, 0, 0, 0)))
}
fn flat(value: &Value) -> String {
    match value {
        Value::Object(map) if !map.is_empty() => format!(
            "{{ {} }}",
            ordered_entries(map)
                .into_iter()
                .map(|(key, value)| format!(
                    "{}: {}",
                    serde_json::to_string(key).unwrap(),
                    flat(value)
                ))
                .collect::<Vec<_>>()
                .join(", ")
        ),
        Value::Array(values) => format!(
            "[{}]",
            values.iter().map(flat).collect::<Vec<_>>().join(", ")
        ),
        Value::Number(_) => compact(value).replace("e+", "e"),
        _ => compact(value),
    }
}
fn width(text: &str) -> usize {
    text.encode_utf16().count()
}
fn layout(value: &Value, depth: usize, column: usize, suffix: usize) -> String {
    let flattened = flat(value);
    if column + width(&flattened) + suffix <= 80 {
        return flattened;
    }
    let indent = "  ".repeat(depth + 1);
    let (open, close, entries): (&str, &str, Vec<(String, &Value)>) = match value {
        Value::Object(map) => (
            "{",
            "}",
            ordered_entries(map)
                .into_iter()
                .map(|(key, v)| (format!("{}: ", serde_json::to_string(key).unwrap()), v))
                .collect(),
        ),
        Value::Array(values) => (
            "[",
            "]",
            values.iter().map(|v| (String::new(), v)).collect(),
        ),
        _ => return flattened,
    };
    let last = entries.len().saturating_sub(1);
    let lines = entries
        .into_iter()
        .enumerate()
        .map(|(index, (prefix, value))| {
            let content = layout(
                value,
                depth + 1,
                width(&indent) + width(&prefix),
                usize::from(index != last),
            );
            format!("{indent}{prefix}{content}")
        })
        .collect::<Vec<_>>()
        .join(",\n");
    format!("{open}\n{lines}\n{}{close}", "  ".repeat(depth))
}
fn union(name: &str, members: &[String]) -> String {
    format!(
        "export type {name} =\n{};\n",
        members
            .iter()
            .map(|s| format!("  | {}", serde_json::to_string(s).unwrap()))
            .collect::<Vec<_>>()
            .join("\n")
    )
}
pub fn render(registry: &Value, fixtures: &Value) -> Result<Vec<(String, String)>> {
    let units: Vec<_> = registry["units"]
        .as_object()
        .unwrap()
        .keys()
        .cloned()
        .collect();
    let measures: Vec<_> = registry["measures"]
        .as_object()
        .unwrap()
        .keys()
        .cloned()
        .collect();
    let dimensions: Vec<_> = registry["dimensions"]
        .as_array()
        .unwrap()
        .iter()
        .map(|s| s.as_str().unwrap().to_owned())
        .collect();
    let mut ts = "// Generated by i5-units-generator. Do not edit.\n".to_owned();
    ts += &union("Unit", &units);
    ts += &union("Measure", &measures);
    ts += &union("Dimension", &dimensions);
    ts += "export interface UnitsByMeasure {\n";
    for measure in &measures {
        ts += &format!("  {}:\n", serde_json::to_string(measure).unwrap());
        ts += &units
            .iter()
            .filter(|unit| registry["units"][*unit]["measure"] == *measure)
            .map(|unit| format!("    | {}", serde_json::to_string(unit).unwrap()))
            .collect::<Vec<_>>()
            .join("\n");
        ts += ";\n";
    }
    ts += "}\nexport type UnitOfMeasure<M extends Measure> = UnitsByMeasure[M];\n";
    let python = format!("# Generated by i5-units-generator. Do not edit.\nfrom typing import Literal\n\nUnit = Literal[\n{}\n]\n", units.iter().map(|u| format!("    {},", serde_json::to_string(u).unwrap())).collect::<Vec<_>>().join("\n"));
    let json = pretty(registry)?;
    Ok(vec![
        ("registry.generated.json".into(), json.clone()),
        (
            "python/src/i5_units/registry.generated.json".into(),
            json.clone(),
        ),
        ("rust/src/registry.generated.json".into(), json),
        ("typescript/src/types.generated.ts".into(), ts),
        ("python/src/i5_units/types_generated.py".into(), python),
        (
            "rust/tests/fixtures.generated.json".into(),
            pretty(fixtures)?,
        ),
    ])
}
